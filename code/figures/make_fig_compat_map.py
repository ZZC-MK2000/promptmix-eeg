"""Fig 8 (CPU): full tolerance map -- zero-crossing rate of every one of the C(12,2)=66 prompt
pairs generated by interpolating their T5 embeddings at alpha=0.5. Reads the cached sweep result,
so it adds no GPU time.

Run: python code/figures/make_fig_compat_map.py
"""
import json
import sys
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path("D:/Projects/CLaBraM/promptmix-eeg")
sys.path.insert(0, str(Path(__file__).parent))
from figstyle import TITLE_FS, save

K = 12
SHORT = ["bolly-dance", "ind-ballad", "pop", "r&b", "edm", "acoustic",
         "funk", "reggaeton", "ambient", "rock", "trap", "orch-cue"]


def main():
    c = json.load(open(ROOT / "results" / "library_b" / "compat" / "compat.json", encoding="utf-8"))
    M = np.full((K, K), np.nan)
    for r in c["rows"]:
        i, j = r["pair"]
        M[i, j] = M[j, i] = r["zcr"]
    n_safe = sum(1 for r in c["rows"] if r["safe"])
    n_dang = sum(1 for r in c["rows"] if r["dangerous"])

    fig, ax = plt.subplots(figsize=(7.6, 6.4))
    im = ax.imshow(M, cmap="RdYlGn_r", vmin=0, vmax=np.nanmax(M))
    for i in range(K):
        for j in range(K):
            if not np.isnan(M[i, j]):
                ax.text(j, i, f"{M[i, j]:.2f}", ha="center", va="center", fontsize=7,
                        color="#222" if M[i, j] < 0.28 else "white")
    ax.set_xticks(range(K)); ax.set_xticklabels(SHORT, rotation=55, ha="right", fontsize=8)
    ax.set_yticks(range(K)); ax.set_yticklabels(SHORT, fontsize=8)
    ax.set_title(f"Tolerance map: all {c['n_pairs']} prompt pairs interpolated at alpha=0.5\n"
                 f"{n_safe / len(c['rows']):.0%} safe (zcr<=0.06) vs "
                 f"{n_dang / len(c['rows']):.0%} off-manifold (zcr>{c['danger']})",
                 fontsize=TITLE_FS)
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.03).set_label("zero-crossing rate", fontsize=8.5)
    fig.tight_layout(); save(fig, "fig8_tolerance_map.png")
    print(f"pairs={c['n_pairs']} safe={n_safe} dangerous={n_dang}")


if __name__ == "__main__":
    main()
